/** Fator de atualização do ano do dado até ANO_REF_SALARIO: produto de (1 + inflação) dos anos seguintes ao do dado.
 *  Anos sem dado contam como inflação zero (e são informados em `faltam`). */
export function fatorInflacao(iso: string | undefined, ano: number | null | undefined): { fator: number; de: number; ate: number; faltam: number } | null {
  if (!iso || !ano || ano >= ANO_REF_SALARIO) return null;
  const serie = INFLACAO_FMI[iso]; if (!serie) return null;
  let fator = 1, faltam = 0;
  for (let y = Math.max(ano + 1, ANO_INICIAL_INFLACAO); y <= ANO_REF_SALARIO; y++) {
    const v = serie[y - ANO_INICIAL_INFLACAO];
    if (typeof v === 'number') fator *= 1 + v / 100; else faltam++;
  }
  return { fator, de: ano, ate: ANO_REF_SALARIO, faltam };
}
